/**
 * تأخير ظهور العنصر عند التمرير — بيتحط كـ inline style
 * والـ CSS بيقراه من المتغيّر --rd.
 */
export function revealDelay(ms: number): React.CSSProperties {
  return { '--rd': `${ms}ms` } as React.CSSProperties
}
