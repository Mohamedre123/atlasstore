/** بيرجع لون فعلي للاسم، أو null لو الاسم مش لون معروف */
export function colorOf(name: string): string | null {
  const clean = name.trim()
  return MAP[clean] ?? MAP[clean.replace(/^ال/, '')] ?? null
}

/** true لو المجموعة دي مجموعة ألوان (عشان نعرضها كنقط) */
export function isColorGroup(groupName: string): boolean {
  return groupName.trim() === 'اللون'
}
