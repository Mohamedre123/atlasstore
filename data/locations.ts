/** أسماء المحافظات فقط */
export const governorateNames: string[] = governorates.map((g) => g.name)

/** مراكز/أحياء محافظة معيّنة */
export function getAreas(governorateName: string): string[] {
  return governorates.find((g) => g.name === governorateName)?.areas ?? []
}

/** التحقق إن المحافظة موجودة */
export function isValidGovernorate(name: string): boolean {
  return governorates.some((g) => g.name === name)
}

/** التحقق إن المركز تابع للمحافظة فعلًا */
export function isValidArea(governorateName: string, areaName: string): boolean {
  return getAreas(governorateName).includes(areaName)
}

/**
 * سعر الشحن — موحّد لكل المحافظات.
 * بيرجع null لو العميل لسه ما اختارش محافظة، عشان الخانة تفضل فاضية.
 */
export function getShippingCost(governorateName?: string): number | null {
  if (!governorateName) return null
  return SHIPPING_FLAT_RATE
}
